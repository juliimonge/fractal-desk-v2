"""The only implementation of :class:`SubmissionBackend` in this repository.

===========================================================================
THIS IS A MOCK. IT RETURNS CANNED RESPONSES FROM A DICTIONARY.
IT CANNOT SIGN. IT CANNOT TRANSMIT. IT HAS NOWHERE TO TRANSMIT TO.
===========================================================================

``sign()`` prepends a marker to the bytes it was given and hands them back. It
performs no cryptography — there is no key, no certificate, no XAdES library
call and no PIN. ``submit()`` writes to an in-memory dictionary. ``poll_status``
reads that dictionary back. No socket is opened at any point, by any method, on
any code path.

The mock is deterministic: the same clave always produces the same outcome. That
matters for tests, and it matters for demonstrating the interface without
anybody wondering whether a "random failure" was actually a network call.

The XML this produces is a *sketch* of an acceptance message — enough to show
the shape of the problem and to give the lxml dependency something real to
parse. It is deliberately not schema-complete, because a schema-complete
acceptance message builder is the one piece that would make this repository
genuinely dangerous if someone bolted a signer onto it.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from lxml import etree

from .interface import (
    AcceptanceMessageType,
    SubmissionBackend,
    SubmissionReceipt,
    SubmissionState,
)

# Marker written into every artefact this module produces. If a byte string
# produced here ever turned up somewhere it should not, this is what identifies
# it.
MOCK_MARKER = b"<!-- SYNTHETIC MOCK ARTEFACT - NOT A VALID ELECTRONIC DOCUMENT -->"
MOCK_SIGNATURE_PREFIX = b"MOCK-SIGNATURE-NOT-CRYPTOGRAPHIC:"


class MockSubmissionBackend(SubmissionBackend):
    """Canned-response backend. See module docstring."""

    is_mock = True

    def __init__(self) -> None:
        self._submitted: dict[str, SubmissionReceipt] = {}
        self.call_log: list[tuple[str, str]] = []

    # ------------------------------------------------------------------

    def build_xml(self, document: Any, message_type: AcceptanceMessageType) -> bytes:
        """Sketch an acceptance message. Not schema-complete, by design."""
        self.call_log.append(("build_xml", getattr(document, "clave", "?")))

        root = etree.Element("MensajeReceptor")
        etree.SubElement(root, "Clave").text = str(document.clave)
        etree.SubElement(root, "NumeroCedulaEmisor").text = str(document.issuer_id)
        etree.SubElement(root, "FechaEmisionDoc").text = document.issue_datetime.isoformat()
        etree.SubElement(root, "Mensaje").text = message_type.value
        etree.SubElement(root, "MontoTotalImpuesto").text = str(document.total_tax)
        etree.SubElement(root, "TotalFactura").text = str(document.total_document)
        etree.SubElement(root, "NumeroCedulaReceptor").text = str(document.receiver_id or "")
        # Every artefact says what it is, inside the artefact.
        etree.SubElement(root, "SyntheticDataNotice").text = (
            "SYNTHETIC TEST DATA - generated by fractal-desk-v2 - not a real document"
        )

        body = etree.tostring(root, pretty_print=True, encoding="UTF-8", xml_declaration=True)
        return MOCK_MARKER + b"\n" + body

    def sign(self, xml_bytes: bytes) -> bytes:
        """NOT A SIGNATURE. Prepends a marker and returns the input unchanged.

        A real implementation would apply a XAdES-EPES enveloped signature using
        the taxpayer's Hacienda-issued cryptographic key. This repository holds
        no key and imports no signing library. Nothing about this method can be
        configured into doing real cryptography.
        """
        self.call_log.append(("sign", f"{len(xml_bytes)} bytes"))
        return MOCK_SIGNATURE_PREFIX + xml_bytes

    def submit(self, signed_xml: bytes, *, clave: str) -> SubmissionReceipt:
        """Records to an in-memory dict. Opens no connection.

        The refusal below is not defence-in-depth theatre — it is the check that
        makes the mock's contract enforceable. Anything that reaches this method
        without having gone through this class's own ``sign`` is not a payload
        this backend produced, and the mock declines to pretend otherwise.
        """
        if not signed_xml.startswith(MOCK_SIGNATURE_PREFIX):
            raise ValueError(
                "Refusing to submit: payload was not produced by MockSubmissionBackend.sign. "
                "This backend only ever handles its own mock artefacts."
            )

        self.call_log.append(("submit", clave))
        receipt = SubmissionReceipt(
            clave=clave,
            state=SubmissionState.SUBMITTED,
            submitted_at=datetime(2026, 1, 1, 12, 0, 0),  # fixed: mocks do not read clocks
            message="Mock submission recorded in memory. No network activity occurred.",
            is_mock=True,
            detail={"backend": "MockSubmissionBackend", "transport": "none"},
        )
        self._submitted[clave] = receipt
        return receipt

    def poll_status(self, clave: str) -> SubmissionReceipt:
        """Returns a canned verdict, deterministic per clave."""
        self.call_log.append(("poll_status", clave))

        if clave not in self._submitted:
            return SubmissionReceipt(
                clave=clave,
                state=SubmissionState.ERROR,
                submitted_at=None,
                message="No mock submission recorded for this clave.",
                is_mock=True,
            )

        # Deterministic outcome so tests and demos are reproducible. The 5% /
        # 10% split gives the three real outcomes something to stand for without
        # pretending to model anything.
        bucket = sum(ord(c) for c in clave) % 20
        if bucket == 0:
            state, message = SubmissionState.REJECTED, "Mock verdict: rechazado."
        elif bucket in (1, 2):
            state, message = (
                SubmissionState.PARTIALLY_ACCEPTED,
                "Mock verdict: aceptado parcial.",
            )
        else:
            state, message = SubmissionState.ACCEPTED, "Mock verdict: aceptado."

        return SubmissionReceipt(
            clave=clave,
            state=state,
            submitted_at=self._submitted[clave].submitted_at,
            message=f"{message} Canned response; no tax authority was contacted.",
            is_mock=True,
            detail={"backend": "MockSubmissionBackend", "bucket": bucket},
        )
